def run_experiment():
    L = 10.0
    nx = ny = 64
    omega = 0.2           # harmonic trap frequency
    T = 2.0
    dt_list = [0.01, 0.04, 0.08]
    regimes = [("linear", 0.0), ("nonlinear", 50.0)]
    print("CPU logical cores:", os.cpu_count())
    x, y, X, Y, dx, dy = build_grid(L=L, nx=nx, ny=ny)
    V = 0.5 * omega ** 2 * (X ** 2 + Y ** 2)
    KX, KY, K2 = build_spectral_operators(nx, ny, dx, dy)
    psi0 = initial_wavepacket(x, y)
    M0 = compute_mass(psi0, dx, dy)
    print("Initial mass M0 = %.16f" % M0)
    results = []
    final_states = {}
    for regime_name, g in regimes:
        print("\nRegime: %s (g = %.3f)" % (regime_name, g))
        for dt in dt_list:
            t_start = time.perf_counter()

            psiT, t_hist, mass_hist, energy_hist = splitstep_gpe_2d(
                psi0, V, g, dt, T, x, y, KX, KY, K2
            )

            cpu = time.perf_counter() - t_start
            max_mass_err = float(np.max(np.abs(mass_hist - M0)))
            E0 = float(energy_hist[0])
            ET = float(energy_hist[-1])

            results.append(
                {
                    "regime": regime_name,
                    "g": g,
                    "dt": dt,
                    "cpu": cpu,
                    "M_final": float(mass_hist[-1]),
                    "max_mass_err": max_mass_err,
                    "E0": E0,
                    "ET": ET,
                    "E_diff": abs(ET - E0),
                }
            )

            final_states[(regime_name, dt)] = psiT

            print(
                "  dt = %.3f, steps = %4d, cpu = %.3fs, "
                "max |M(t)-M0| = %.3e, |E(T)-E(0)| = %.3e"
#                 % (dt, len(t_hist) - 1, cpu, max_mass_err, abs(ET - E0))
            )

            if abs(dt - dt_list[0]) < 1e-12:
                save_plots_for_run(
                    regime_name, dt, x, y, psiT, t_hist, mass_hist, energy_hist
                )

    compute_speedup(results)
    run_verification_tests(results)
    write_summary(results)
    plot_speedup(results)
    plot_error_maps(final_states, x, y)

    print("\nSummary written to results_summary.txt and results_summary.csv")
    print("Additional plots: speedup_vs_dt.png, error_*_dt0.08_vs_dt0.01.png")



if __name__ == "__main__":
    run_experiment()